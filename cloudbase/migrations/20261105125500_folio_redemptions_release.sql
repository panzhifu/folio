-- 解除激活：**软解除**，留一列时间戳，不删行。
--
-- 删行等于抹掉「这一单兑过」这个事实，而兑换防重的全部根据就是主键撞上旧记录 —— 行没了，
-- 同一单再兑一次就又是一整笔天数；「解除 → 重兑 → 再解除」一轮几分钟，365 天能刷成无限。
-- 留着那一行，这一单之后只能被**认领**（把 device 换成新的那一台），搬过去的是剩下的那几天。
--
-- 可空、无默认：老行读回来就是「没被解除过」，不必回填，也不给已生效的兑换改形状。
