//! 书怎么进来：从外部的一堆字节，到库里一行「可打开的记录」。
//!
//! - [`import`] —— 导入管线：`Source` trait 一条抽象七种来源（选文件 / 批量 /
//!   整机扫描 / 监听 / Wi-Fi 传书 / URL / WebDAV），逐本「拷 → 哈希 → 判定 →
//!   判重 → 落地 → 解析 → 落库」。设计见 `plans/导入管线.md`。
//! - [`scan`] —— 整机扫描：**找书不导入**，候选清单勾选后再走管线。
//! - [`watch`] —— 文件夹监听：inotify 事件攒批自动入库（`notify`）。
//! - [`identity`] —— 书的身份：内容哈希（书的身份是它的内容，不是文件路径）。
//!
//! 这一区是**唯一**允许同时碰容器、文件系统与数据库的地方 —— 它的产物就是
//! [`crate::store`] 里的那些行。阅读路径上不再有「按格式分支」这回事
//! （见 [`crate::content`]）。

pub mod identity;
pub mod import;
pub mod scan;
pub mod watch;
